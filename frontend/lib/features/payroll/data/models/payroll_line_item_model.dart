import '../../domain/entities/payroll_line_item.dart';

class PayrollLineItemModel extends PayrollLineItem {
  const PayrollLineItemModel({
    required super.id,
    required super.employeeId,
    required super.freelancerId,
    required super.isFreelancer,
    required super.employeeName,
    required super.employeePhotoUrl,
    required super.baseSalary,
    required super.quantity,
    required super.perUnitRate,
    required super.allowances,
    required super.overtime,
    required super.reimbursement,
    required super.commissions,
    required super.deductions,
    required super.advances,
    required super.tax,
    required super.fines,
    required super.totalAbsent,
    required super.absentDeductionRs,
    required super.lateHours,
    required super.lateHoursDeductionRs,
    required super.lateDays,
    required super.lateDaysDeductionRs,
    required super.netPay,
    required super.notes,
  });

  factory PayrollLineItemModel.fromJson(Map<String, dynamic> json) =>
      PayrollLineItemModel(
        id: json['id'] as String,
        employeeId: json['employeeId'] as String?,
        freelancerId: json['freelancerId'] as String?,
        isFreelancer: json['isFreelancer'] as bool,
        employeeName: json['employeeName'] as String,
        employeePhotoUrl: json['employeePhotoUrl'] as String?,
        baseSalary: (json['baseSalary'] as num).toDouble(),
        quantity: json['quantity'] as int?,
        perUnitRate: (json['perUnitRate'] as num?)?.toDouble(),
        allowances: (json['allowances'] as num).toDouble(),
        overtime: (json['overtime'] as num).toDouble(),
        reimbursement: (json['reimbursement'] as num).toDouble(),
        commissions: (json['commissions'] as num).toDouble(),
        deductions: (json['deductions'] as num).toDouble(),
        advances: (json['advances'] as num).toDouble(),
        tax: (json['tax'] as num).toDouble(),
        fines: (json['fines'] as num).toDouble(),
        totalAbsent: json['totalAbsent'] as int,
        absentDeductionRs: (json['absentDeductionRs'] as num).toDouble(),
        lateHours: json['lateHours'] as int,
        lateHoursDeductionRs: (json['lateHoursDeductionRs'] as num).toDouble(),
        lateDays: json['lateDays'] as int,
        lateDaysDeductionRs: (json['lateDaysDeductionRs'] as num).toDouble(),
        netPay: (json['netPay'] as num).toDouble(),
        notes: json['notes'] as String?,
      );
}
