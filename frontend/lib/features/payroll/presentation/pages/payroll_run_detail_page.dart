class PayrollRunDetailPage extends ConsumerWidget {
  const PayrollRunDetailPage({super.key, required this.runId});

  final String runId;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final runAsync = ref.watch(payrollRunDetailProvider(runId));

    return Scaffold(
      appBar: AppBar(title: const Text('Payroll Run')),
      body: Padding(
        padding: const EdgeInsets.all(20),
        child: Center(
          child: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 1000),
            child: runAsync.when(
              loading: () => const Center(child: CircularProgressIndicator()),
              error: (_, _) => Text(
                'Could not load this payroll run. Please try again.',
                style: TextStyle(color: Theme.of(context).colorScheme.error),
              ),
              data: (run) => _RunDetailBody(run: run),
            ),
          ),
        ),
      ),
    );
  }
}

class _RunDetailBody extends ConsumerWidget {
