class _EditLineItemDialog extends ConsumerStatefulWidget {
  const _EditLineItemDialog({required this.runId, required this.item});

  final String runId;
  final PayrollLineItem item;

  @override
  ConsumerState<_EditLineItemDialog> createState() =>
      _EditLineItemDialogState();
}

class _EditLineItemDialogState extends ConsumerState<_EditLineItemDialog> {
  late final TextEditingController _baseSalaryController;
  late final TextEditingController _quantityController;
  late final TextEditingController _perUnitRateController;
  late final TextEditingController _additionsController;
  late final TextEditingController _deductionsController;
  late final TextEditingController _notesController;
  bool _saving = false;
  String? _errorMessage;

  @override
  void initState() {
    super.initState();
    _baseSalaryController = TextEditingController(
      text: widget.item.baseSalary.toStringAsFixed(2),
    );
    _quantityController = TextEditingController(
      text: widget.item.quantity == null ? '' : '${widget.item.quantity}',
    );
    _perUnitRateController = TextEditingController(
      text: widget.item.perUnitRate?.toStringAsFixed(2) ?? '',
    );
    _additionsController = TextEditingController(
      text: widget.item.additions.toStringAsFixed(2),
    );
    _deductionsController = TextEditingController(
      text: widget.item.deductions.toStringAsFixed(2),
    );
    _notesController = TextEditingController(text: widget.item.notes ?? '');
    for (final controller in [
      _baseSalaryController,
      _quantityController,
      _perUnitRateController,
      _additionsController,
      _deductionsController,
    ]) {
      controller.addListener(_onFieldChanged);
    }
  }

  void _onFieldChanged() => setState(() {});

  /// Mirrors the backend mapper: Quantity × Per unit replaces the salary
  /// snapshot as this run's base pay when both are set, then
  /// additions/deductions are applied on top — kept in sync here purely so
  /// the dialog can preview Net Pay live as the admin types.
  double get _previewNetPay {
    final quantity = int.tryParse(_quantityController.text);
    final perUnitRate = double.tryParse(_perUnitRateController.text);
    final baseSalary = double.tryParse(_baseSalaryController.text) ?? 0;
    final effectiveBase = (quantity != null && quantity > 0 && perUnitRate != null)
        ? quantity * perUnitRate
        : baseSalary;
    final additions = double.tryParse(_additionsController.text) ?? 0;
    final deductions = double.tryParse(_deductionsController.text) ?? 0;
    return effectiveBase + additions - deductions;
  }

  @override
  void dispose() {
    _baseSalaryController.dispose();
    _quantityController.dispose();
    _perUnitRateController.dispose();
    _additionsController.dispose();
    _deductionsController.dispose();
    _notesController.dispose();
    super.dispose();
  }

  Future<void> _submit() async {
    setState(() {
      _saving = true;
      _errorMessage = null;
    });
    try {
      await ref
          .read(payrollRepositoryProvider)
          .updateLineItem(
            widget.runId,
            widget.item.id,
            baseSalary: widget.item.isFreelancer
                ? double.tryParse(_baseSalaryController.text)
                : null,
            quantity: int.tryParse(_quantityController.text),
            perUnitRate: double.tryParse(_perUnitRateController.text),
            additions: double.tryParse(_additionsController.text),
            deductions: double.tryParse(_deductionsController.text),
            notes: _notesController.text.trim().isEmpty
                ? null
                : _notesController.text.trim(),
          );
      if (mounted) Navigator.of(context).pop();
    } on PayrollException catch (error) {
      setState(() => _errorMessage = error.message);
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      title: Text(widget.item.employeeName),
      content: SizedBox(
        width: 380,
        child: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              if (_errorMessage != null) ...[
                Text(
                  _errorMessage!,
                  style: TextStyle(color: Theme.of(context).colorScheme.error),
                ),
                const SizedBox(height: 12),
              ],
              if (widget.item.isFreelancer) ...[
                const _SectionLabel('Amount'),
                const SizedBox(height: 8),
                _AmountField(
                  label: 'This month\'s pay',
                  controller: _baseSalaryController,
                  enabled: !_saving,
                ),
              ] else
                Text(
                  'Salary snapshot: PKR ${formatAmount(widget.item.baseSalary)}',
                  style: Theme.of(context).textTheme.bodySmall?.copyWith(
                    color: AppColors.textSecondary,
                  ),
                ),
              const SizedBox(height: 16),
              const _SectionLabel('Piece-rate pay (optional)'),
              const SizedBox(height: 8),
              Row(
                children: [
                  Expanded(
                    child: TextField(
                      controller: _quantityController,
                      enabled: !_saving,
                      keyboardType: TextInputType.number,
                      decoration: const InputDecoration(labelText: 'Quantity'),
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: _AmountField(
                      label: 'Per unit',
                      controller: _perUnitRateController,
                      enabled: !_saving,
                    ),
                  ),
                ],
              ),
              Padding(
                padding: const EdgeInsets.only(top: 4),
                child: Text(
                  'When both are set, Quantity × Per unit replaces the salary '
                  'snapshot as this run\'s base pay.',
                  style: Theme.of(context).textTheme.labelSmall?.copyWith(
                    color: AppColors.textSecondary,
                  ),
                ),
              ),
              const SizedBox(height: 16),
              const _SectionLabel('Additions & Deductions'),
              const SizedBox(height: 8),
              Row(
                children: [
                  Expanded(
                    child: _AmountField(
                      label: 'Additions',
                      controller: _additionsController,
                      enabled: !_saving,
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: _AmountField(
                      label: 'Deductions',
                      controller: _deductionsController,
                      enabled: !_saving,
                    ),
                  ),
                ],
              ),
              Padding(
                padding: const EdgeInsets.only(top: 4),
                child: Text(
                  'Net Pay = Base + Additions − Deductions: '
                  'PKR ${formatAmount(_previewNetPay)}',
                  style: Theme.of(context).textTheme.labelMedium?.copyWith(
                    fontWeight: FontWeight.w600,
                    color: AppColors.primary,
                  ),
                ),
              ),
              const SizedBox(height: 16),
              TextField(
                controller: _notesController,
                enabled: !_saving,
                maxLines: 2,
                decoration: const InputDecoration(labelText: 'Notes (optional)'),
              ),
            ],
          ),
        ),
      ),
      actions: [
        TextButton(
          onPressed: _saving ? null : () => Navigator.of(context).pop(),
          child: const Text('Cancel'),
        ),
        FilledButton(
          onPressed: _saving ? null : _submit,
          child: _saving
              ? const SizedBox(
                  height: 16,
                  width: 16,
                  child: CircularProgressIndicator(strokeWidth: 2),
                )
              : const Text('Save'),
        ),
      ],
    );
  }
}

class _AddFreelancerDialog extends ConsumerStatefulWidget {
  const _AddFreelancerDialog({required this.run});

  final PayrollRunDetail run;

  @override
  ConsumerState<_AddFreelancerDialog> createState() =>
      _AddFreelancerDialogState();
}

class _AddFreelancerDialogState extends ConsumerState<_AddFreelancerDialog> {
  String? _selectedFreelancerId;
  final _amountController = TextEditingController();
  final _notesController = TextEditingController();
  bool _saving = false;
  String? _errorMessage;

  @override
  void dispose() {
    _amountController.dispose();
    _notesController.dispose();
    super.dispose();
  }

  Future<void> _submit() async {
    final freelancerId = _selectedFreelancerId;
    if (freelancerId == null) return;
    setState(() {
      _saving = true;
      _errorMessage = null;
    });
    try {
      await ref
          .read(payrollRepositoryProvider)
          .addFreelancerToRun(
            widget.run.id,
            freelancerId: freelancerId,
            baseSalary: double.tryParse(_amountController.text) ?? 0,
            notes: _notesController.text.trim().isEmpty
                ? null
                : _notesController.text.trim(),
          );
      if (mounted) Navigator.of(context).pop();
    } on PayrollException catch (error) {
      setState(() => _errorMessage = error.message);
    } finally {
      if (mounted) setState(() => _saving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final freelancersAsync = ref.watch(freelancersListProvider);
    final alreadyInRun = widget.run.lineItems
        .map((item) => item.freelancerId)
        .whereType<String>()
        .toSet();

    return AlertDialog(
      title: const Text('Add Freelancer'),
      content: SizedBox(
        width: 380,
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            if (_errorMessage != null) ...[
              Text(
                _errorMessage!,
                style: TextStyle(color: Theme.of(context).colorScheme.error),
              ),
              const SizedBox(height: 12),
            ],
            freelancersAsync.when(
              loading: () => const Center(child: CircularProgressIndicator()),
              error: (_, _) => const Text('Could not load freelancers.'),
              data: (freelancers) {
                final available = freelancers
                    .where((f) => f.isActive && !alreadyInRun.contains(f.id))
                    .toList();
                if (available.isEmpty) {
                  return Text(
                    'No active freelancers left to add — everyone active is '
                    'already in this run.',
                    style: Theme.of(context).textTheme.bodyMedium?.copyWith(
                      color: AppColors.textSecondary,
                    ),
                  );
                }
                return DropdownButtonFormField<String>(
                  initialValue: _selectedFreelancerId,
                  decoration: const InputDecoration(labelText: 'Freelancer'),
                  items: [
                    for (final freelancer in available)
                      DropdownMenuItem(
                        value: freelancer.id,
                        child: Text(freelancer.fullName),
                      ),
                  ],
                  onChanged: _saving
                      ? null
                      : (value) =>
                            setState(() => _selectedFreelancerId = value),
                );
              },
            ),
            const SizedBox(height: 12),
            _AmountField(
              label: "This month's pay",
              controller: _amountController,
              enabled: !_saving,
            ),
            const SizedBox(height: 12),
            TextField(
              controller: _notesController,
              enabled: !_saving,
              maxLines: 2,
              decoration: const InputDecoration(labelText: 'Notes (optional)'),
            ),
          ],
        ),
      ),
      actions: [
        TextButton(
          onPressed: _saving ? null : () => Navigator.of(context).pop(),
          child: const Text('Cancel'),
        ),
        FilledButton(
          onPressed: (_saving || _selectedFreelancerId == null)
              ? null
              : _submit,
          child: _saving
              ? const SizedBox(
                  height: 16,
                  width: 16,
                  child: CircularProgressIndicator(strokeWidth: 2),
                )
              : const Text('Add'),
        ),
      ],
    );
  }
}

class _SectionLabel extends StatelessWidget {
  const _SectionLabel(this.text);

  final String text;

  @override
  Widget build(BuildContext context) {
    return Text(
      text.toUpperCase(),
      style: Theme.of(context).textTheme.labelSmall?.copyWith(
        color: AppColors.textSecondary,
        fontWeight: FontWeight.w700,
        letterSpacing: 0.4,
      ),
    );
  }
}

class _AmountField extends StatelessWidget {
  const _AmountField({
    required this.label,
    required this.controller,
    required this.enabled,
  });

  final String label;
  final TextEditingController controller;
  final bool enabled;

  @override
  Widget build(BuildContext context) {
    return TextField(
      controller: controller,
      enabled: enabled,
      keyboardType: const TextInputType.numberWithOptions(decimal: true),
      decoration: InputDecoration(labelText: '$label (PKR)'),
    );
  }
}
